import { test, expect } from '@playwright/test';
for (const width of [320,390,768,1366]) test(`criação, falha e recuperação preservam a ficha em ${width}px`, async ({page}) => {
  await page.setViewportSize({width,height:900});
  await page.goto('/qa/fitness-editor-harness.html');
  await page.getByRole('button',{name:'Criar ficha de treino'}).click();
  await page.getByLabel('Nome da ficha').fill('Treino de teste');
  if(width<=760) await page.getByRole('button',{name:'Adicionar exercício',exact:true}).click();
  await page.getByLabel('Buscar exercício',{exact:true}).fill('Supino reto com barra');
  await page.getByRole('button',{name:'Adicionar Supino reto com barra',exact:true}).click();
  await page.getByRole('button',{name:'Treino B',exact:true}).click();
  await page.getByLabel('Buscar exercício',{exact:true}).fill('Leg press');
  await page.getByRole('button',{name:'Adicionar Leg press',exact:true}).click();
  await page.getByLabel('Repetições de Leg press').fill('10');
  await page.getByText('Orientações e detalhes').click();
  await page.getByLabel('Carga ou esforço',{exact:true}).fill('moderado');
  await page.getByLabel('Instruções',{exact:true}).fill('Movimento controlado');
  await page.getByLabel('Alternativa',{exact:true}).fill('Outra opção');
  await page.getByRole('button',{name:/Treino A/}).click();
  await page.getByLabel('Repetições de Supino reto com barra').fill('8 a 10');
  await page.getByText('Orientações e detalhes').click();
  await page.getByLabel('Carga ou esforço',{exact:true}).fill('moderado');
  await page.getByLabel('Instruções',{exact:true}).fill('Movimento controlado');
  await page.getByLabel('Alternativa',{exact:true}).fill('Outra opção');
  await page.evaluate(()=>sessionStorage.setItem('fail-save','yes'));
  await page.getByRole('button',{name:'Salvar rascunho'}).click();
  await expect(page.getByRole('alert')).toContainText('Falha de teste ao salvar');
  await expect(page.getByLabel('Nome da ficha')).toHaveValue('Treino de teste');
  await page.evaluate(()=>sessionStorage.removeItem('fail-save'));
  await page.getByRole('button',{name:'Salvar rascunho'}).click();
  await expect(page.getByText('Ficha em rascunho salva no servidor.')).toBeVisible();
  await page.getByRole('button',{name:'Revisar e editar'}).click();
  await expect(page.getByLabel('Repetições de Supino reto com barra')).toHaveValue('8 a 10');
  await page.getByText('Orientações e detalhes').click();
  await page.getByText('Músculos, mídia e outros detalhes').click();
  await expect(page.getByRole('button',{name:'Supino reto com barra Peito · 2D'})).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button',{name:/Treino B/}).click();
  await expect(page.getByLabel('Repetições de Leg press')).toHaveValue('10');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
});


test('adapta uma cópia sem modificar a ficha aprovada', async ({page}) => {
  await page.goto('/qa/fitness-editor-harness.html?approved=1');
  await page.getByRole('button',{name:'Criar cópia para adaptar'}).click();
  await expect(page.getByRole('heading',{name:'Criar ficha de treino'})).toBeVisible();
  await page.getByLabel('Nome da ficha').fill('Ficha adaptada');
  await expect(page.getByLabel('Repetições de Exercício existente')).toHaveValue('10');
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'Cancelar'}).click();
  await expect(page.getByRole('heading',{name:'Básico · Ficha aprovada'})).toBeVisible();
});
