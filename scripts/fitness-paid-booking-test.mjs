import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

export async function testPaidBooking({db,rpc,session,store,other,owner,student,student2}) {
  await session(owner);
  const service=(await rpc('food_business_operate',[store,'services.save',JSON.stringify({name:'Avaliação de teste',kind:'training',price_cents:5000,duration_minutes:60,active:true})])).item;
  await rpc('food_service_professional_assign',[store,service.id,owner]);
  await rpc('food_fitness_publish_service',[store,service.id,'Cancelamento com 24 horas de antecedência.','Reagendamento com 24 horas de antecedência.',1440,true]);
  const day=new Date(Date.now()+10*86400000).toISOString().slice(0,10);
  await rpc('food_fitness_save_window',[store,null,owner,new Date(day+'T12:00:00Z').getUTCDay(),'13:00','18:00','America/Sao_Paulo',60,0]);
  const offer=(await rpc('food_fitness_offer_save_v1',[store,null,'assessment','Avaliação de teste','Descrição e regras de teste',5000,null,service.id,owner,false])).id;
  await assert.rejects(()=>rpc('food_fitness_offer_save_v1',[store,offer,'assessment','Avaliação de teste','Descrição e regras de teste',5000,null,service.id,owner,true]),'sem local/termos não publica');
  await rpc('food_fitness_offer_delivery_v1',[store,offer,'personalized','Atendimento de teste após pagamento.','Unidade fictícia de homologação','onsite','Instrução fictícia',60]);
  await rpc('food_fitness_offer_save_v1',[store,offer,'assessment','Avaliação de teste','Descrição e regras de teste',5000,null,service.id,owner,true]);
  const slot=(await rpc('food_fitness_list_slots',[store,service.id,day,1])).slots[0];
  await session(student);
  await rpc('food_fitness_student_authorize_professional',[store,owner,'training',true]);
  const request=randomUUID(),order=await rpc('food_fitness_order_v1',[store,offer,request]);
  assert.equal((await rpc('food_fitness_order_v1',[store,offer,request])).id,order.id);
  await assert.rejects(()=>rpc('food_fitness_paid_book_v1',[store,order.id,slot.starts_at,true]),'pendente não reserva');
  await assert.rejects(()=>rpc('food_fitness_book',[store,service.id,slot.starts_at,owner,true]),'legado não contorna compra paga');
  await session(owner,'authenticated','aal2');
  await rpc('food_fitness_confirm_order_v1',[store,order.id,'confirm']);
  await rpc('food_fitness_confirm_order_v1',[store,order.id,'confirm']);
  await assert.rejects(()=>rpc('food_fitness_offer_delivery_v1',[store,offer,'ready','Alteração de contrato','Outro local','online','',0]),'pedido congela entrega');
  await session(student);
  let mine=(await rpc('food_fitness_my_orders_v1',[store])).find(o=>o.id===order.id);
  assert.equal(mine.fulfillment_state,'booking_pending');
  assert.equal(mine.snapshot.location_label,'Unidade fictícia de homologação');
  await assert.rejects(()=>rpc('food_fitness_paid_book_v1',[other,order.id,slot.starts_at,true]));
  await assert.rejects(()=>rpc('food_fitness_paid_book_v1',[store,order.id,slot.starts_at,false]));
  const appointment=await rpc('food_fitness_paid_book_v1',[store,order.id,slot.starts_at,true]);
  assert.equal((await rpc('food_fitness_paid_book_v1',[store,order.id,slot.starts_at,true])).appointment_id,appointment.appointment_id);
  await session(student2);
  await rpc('food_fitness_student_authorize_professional',[store,owner,'training',true]);
  const second=await rpc('food_fitness_order_v1',[store,offer,randomUUID()]);
  await session(owner,'authenticated','aal2');
  await rpc('food_fitness_confirm_order_v1',[store,second.id,'confirm']);
  await session(student2);
  await assert.rejects(()=>rpc('food_fitness_paid_book_v1',[store,second.id,slot.starts_at,true]),'última vaga não duplica; serial local, concorrência PostgreSQL remota pendente');
  await session(student);
  const available=(await rpc('food_fitness_list_slots',[store,service.id,day,1])).slots;
  await rpc('food_fitness_reschedule',[appointment.appointment_id,available.at(-1).starts_at,owner]);
  await rpc('food_fitness_cancel',[appointment.appointment_id]);
  await assert.rejects(()=>rpc('food_fitness_paid_book_v1',[store,order.id,slot.starts_at,true]),'cancelamento não cria outra entrega');
  await session(owner,'authenticated','aal2');
  await rpc('food_fitness_confirm_order_v1',[store,order.id,'refund']);
  await session(student);
  mine=(await rpc('food_fitness_my_orders_v1',[store])).find(o=>o.id===order.id);
  assert.equal(mine.fulfillment_state,'refunded');
  const cancelled=await rpc('food_fitness_order_v1',[store,offer,randomUUID()]);
  await rpc('food_fitness_order_cancel_v1',[store,cancelled.id]);
  await session(owner,'authenticated','aal2');
  await assert.rejects(()=>rpc('food_fitness_confirm_order_v1',[store,cancelled.id,'confirm']),'Pix tardio após cancelamento exige revisão');
  await db.exec('reset role');
  assert.equal((await db.query('select count(*)::int n from food_fitness_order_notifications where order_id=$1 and event_kind=$2',[order.id,'scheduled'])).rows[0].n,1);
  console.log('OK compra/agenda: pendente, pagamento/replay, snapshot, vaga única, reagendamento, cancelamento e refund.');
}
