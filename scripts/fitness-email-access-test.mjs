import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

// Auth and payments below are isolated local fixtures, never provider requests.
export async function testEmailAccess({db,rpc,session,store,other,owner,manager}) {
  const row=async(sql,args=[]) => (await db.query(sql,args)).rows[0];
  const emailUser=randomUUID(), unverified=randomUUID(), emptyEmail=randomUUID();
  await db.exec('reset role');
  await db.query("insert into auth.users(id,email,email_confirmed_at,phone,raw_user_meta_data) values($1,'email-student@example.invalid',now(),'+5511999997777','{}'),($2,'unverified@example.invalid',null,null,'{\"email_verified\":true}'),($3,'',now(),null,'{}')",[emailUser,unverified,emptyEmail]);
  for(const user of [unverified,emptyEmail]) {
    await session(user);
    await assert.rejects(()=>rpc('food_fitness_student_status_v1',[store]),/VERIFIED_IDENTITY_REQUIRED/);
    await assert.rejects(()=>rpc('food_fitness_register_student',[store,'Aluno sem identidade','']));
  }
  await db.exec('reset role');
  const manual=await row("insert into food_business_clients(store_id,name,email,phone) values($1,'Contato sem vínculo','email-student@example.invalid','+5511888888888') returning id",[store]);
  await session(emailUser);
  assert.equal((await rpc('food_fitness_student_status_v1',[store])).registered,false);
  await assert.rejects(()=>rpc('food_fitness_register_student',[store,'Aluno por email','+5511999997777']),'telefone da conta ainda não confirmado');
  const profile=await rpc('food_fitness_register_student',[store,'Aluno por email','']);
  assert.notEqual(profile.client_id,manual.id,'não apropria contato existente por e-mail');
  assert.equal(profile.professional,false);
  assert.equal((await rpc('food_fitness_register_student',[store,'Aluno por email',''])).client_id,profile.client_id,'cadastro idempotente');
  await db.exec('reset role');
  const contact=await row('select email,phone from food_business_clients where store_id=$1 and id=$2',[store,profile.client_id]);
  assert.equal(contact.email,'email-student@example.invalid'); assert.equal(contact.phone,'');
  assert.equal((await row('select count(*)::int n from food_store_users where user_id=$1',[emailUser])).n,0);
  assert.equal((await row('select count(*)::int n from food_service_professionals where user_id=$1',[emailUser])).n,0);
  await db.query("update food_business_clients set phone='+5511000000000' where store_id=$1 and id=$2",[store,profile.client_id]);
  await session(emailUser);
  await rpc('food_fitness_register_student',[store,'Aluno por email atualizado','']);
  await db.exec('reset role');
  assert.equal((await row('select phone from food_business_clients where id=$1',[profile.client_id])).phone,'+5511000000000','não apaga contato manual');
  await session(emailUser);
  const first=await row('select auth.jwt() claims'); const firstSid=first.claims.session_id;
  assert.equal((await rpc('food_fitness_student_session_v1',[store,profile.client_id,'claim'])).authorized,true);
  assert.deepEqual(await rpc('food_fitness_list_workouts',[store]),[],'cadastro não entrega fichas');
  const secondSid=randomUUID();
  await session(emailUser,'authenticated','aal1',secondSid);
  assert.equal((await rpc('food_fitness_student_session_v1',[store,profile.client_id,'claim'])).reason,'SESSION_LIMIT');
  await session(emailUser,'authenticated','aal1',firstSid);
  await rpc('food_fitness_student_session_v1',[store,profile.client_id,'release']);
  await session(emailUser,'authenticated','aal1',secondSid);
  assert.equal((await rpc('food_fitness_student_session_v1',[store,profile.client_id,'claim'])).authorized,true);
  const otherProfile=await rpc('food_fitness_register_student',[other,'Aluno em outra loja','']);
  assert.notEqual(otherProfile.client_id,profile.client_id);
  await assert.rejects(()=>rpc('food_fitness_student_session_v1',[store,otherProfile.client_id,'claim']));
  await assert.rejects(()=>rpc('food_fitness_student_session_v1',[other,profile.client_id,'claim']));
  await session(owner);
  const workout=await rpc('food_fitness_save_workout',[store,null,'basic','Ficha de teste por e-mail','Apenas teste local',JSON.stringify([{name:'Movimento de teste',sets:1,repetitions:'1',rest_seconds:60,load_or_effort:'Teste',instructions:'Teste isolado',alternative:'Teste'}]),'custom']);
  await rpc('food_fitness_approve_workout',[store,workout.id]);
  const offer=await rpc('food_fitness_offer_save_v1',[store,null,'workout','Oferta por email','Apenas validação local de acesso',100,workout.id,null,owner,true]);
  await session(emailUser,'authenticated','aal1',secondSid);
  await rpc('food_fitness_student_authorize_professional',[store,owner,'training',true]);
  const purchase=await rpc('food_fitness_order_v1',[store,offer.id,randomUUID()]);
  assert.equal((await rpc('food_fitness_list_workouts',[store])).some(w=>w.id===workout.id),false,'pedido pendente não entrega ficha');
  await assert.rejects(()=>rpc('food_fitness_confirm_order_v1',[store,purchase.id,'confirm']));
  await session(manager);
  await assert.rejects(()=>rpc('food_fitness_confirm_order_v1',[store,purchase.id,'confirm']),'MFA preservado');
  await session(owner,'authenticated','aal2');
  await rpc('food_fitness_confirm_order_v1',[store,purchase.id,'confirm']);
  await session(emailUser,'authenticated','aal1',secondSid);
  assert.equal((await rpc('food_fitness_list_workouts',[store])).some(w=>w.id===workout.id),true);
  await assert.rejects(()=>rpc('food_fitness_list_workouts',[other]));
  await db.exec('reset role');
  await db.query('update auth.users set email_confirmed_at=null where id=$1',[emailUser]);
  await session(emailUser,'authenticated','aal1',secondSid);
  await assert.rejects(()=>rpc('food_fitness_student_session_v1',[store,profile.client_id,'check']));
  await assert.rejects(()=>rpc('food_fitness_list_workouts',[store]),'retirada da confirmação bloqueia conteúdo');
  await db.exec('reset role');
  await db.query('update auth.users set email_confirmed_at=now() where id=$1',[emailUser]);
  await db.query("update auth.sessions set not_after=now()-interval '1 minute' where id=$1",[secondSid]);
  await db.exec('set role authenticated');
  await assert.rejects(()=>rpc('food_fitness_student_session_v1',[store,profile.client_id,'check']),'sessão Auth expirada');
  await session(emailUser,'authenticated','aal1',secondSid);
  await rpc('food_fitness_student_session_v1',[store,profile.client_id,'release']);
  await session(emailUser,'authenticated','aal1',firstSid);
  assert.equal((await rpc('food_fitness_student_session_v1',[store,profile.client_id,'claim'])).reason,'SESSION_REVOKED');
  await session(emailUser,'authenticated','aal1',secondSid);
  await db.exec('reset role');
  await db.query("insert into auth.mfa_factors(id,user_id,status,factor_type) values($1,$2,'verified','totp')",[randomUUID(),emailUser]);
  await db.exec('set role authenticated');
  await assert.rejects(()=>rpc('food_fitness_student_status_v1',[store]),'conta com MFA não acessa com AAL1');
  await assert.rejects(()=>rpc('food_fitness_student_session_v1',[store,profile.client_id,'claim']));
  await session(emailUser,'authenticated','aal2',secondSid);
  assert.equal((await rpc('food_fitness_student_status_v1',[store])).registered,true);
  await assert.rejects(()=>rpc('food_fitness_confirm_order_v1',[store,purchase.id,'confirm']),'MFA não transforma aluno em administrador');
  await db.exec('reset role');
  assert.equal((await row("select has_function_privilege('anon','food_fitness_private.identity_verified(uuid)','EXECUTE') allowed")).allowed,false);
  assert.equal((await row('select name from food_business_clients where id=$1',[manual.id])).name,'Contato sem vínculo');
  console.log('OK e-mail Fitness: identidade confirmada, telefone pendente, sessão única/revogada/expirada, isolamento, consentimento, compra simulada e MFA.');
}
