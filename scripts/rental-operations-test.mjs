import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const compiled = ts.transpileModule(readFileSync('src/modules/rentals.ts', 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { rentalSituation, rentalInPeriod } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const now = new Date('2026-11-23T12:00:00Z');
const r = { starts_at: '2026-11-24T12:00:00Z', ends_at: '2026-11-24T18:00:00Z', status: 'reserved' };
assert.equal(rentalSituation(r, now), 'prepare');
const late = { ...r, starts_at: '2026-11-22T12:00:00Z', ends_at: '2026-11-22T18:00:00Z' };
assert.equal(rentalSituation(late, now), 'unrecorded');
assert.equal(rentalSituation({ ...late, checked_out_at: late.starts_at }, now), 'overdue');
assert.equal(rentalSituation({ ...late, checked_out_at: late.starts_at, status: 'cancelled' }, now), 'overdue');
assert.equal(rentalSituation({ ...late, checked_out_at: late.starts_at, returned_at: now.toISOString() }, now), 'returned');
assert.equal(rentalSituation({ ...r, status: 'cancelled' }, now), 'cancelled');
assert.equal(rentalSituation({ ...r, status: 'returned' }, now), 'unrecorded');
assert.equal(rentalSituation({ ...r, checked_out_at: now.toISOString() }, now), 'in_use');
assert.equal(rentalSituation({ ...r, checked_out_at: now.toISOString(), ends_at: '2026-11-23T18:00:00Z' }, now), 'return_due');
assert.equal(rentalInPeriod(r, Date.parse(r.ends_at), Date.parse(r.ends_at) + 3600000), false);
assert.equal(rentalInPeriod({ ...late, checked_out_at: late.starts_at }, now.getTime() - 3600000, now.getTime() + 3600000, now.getTime()), true);
assert.equal(rentalInPeriod(late, now.getTime() - 3600000, now.getTime() + 3600000, now.getTime()), false);
console.log('12 verificações de situação, atraso e períodos aprovadas.');
